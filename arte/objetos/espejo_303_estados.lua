local function imagen(rows)
  local img = Image(spr.width, spr.height, ColorMode.RGB)
  for y = 1, #rows do
    local r = rows[y]
    for x = 1, #r do
      local c = r:sub(x, x)
      if c ~= "." then img:drawPixel(x - 1, y - 1, COLORES[c]) end
    end
  end
  return img
end

app.transaction("Espejo 303: estados", function()
  local rangos = {}
  for _, f in ipairs(FRAMES) do
    local fr = spr:newEmptyFrame(#spr.frames + 1)
    fr.duration = f.ms / 1000
    spr:newCel(capa, fr, imagen(f.rows), Point(0, 0))
    local r = rangos[f.tag]
    if not r then rangos[f.tag] = { desde = fr.frameNumber, hasta = fr.frameNumber }
    else r.hasta = fr.frameNumber end
  end
  local function tag(nombre, desde, hasta, rep)
    local t = spr:newTag(desde, hasta)
    t.name = nombre
    t.aniDir = AniDir.FORWARD
    t.repeats = rep
  end
  tag("apagado", 1, 1, 0)
  tag("encendido", rangos.encendido.desde, rangos.encendido.hasta, 0)
  tag("calibrando", rangos.calibrando.desde, rangos.calibrando.hasta, 0)
  tag("error", rangos.error.desde, rangos.error.hasta, 2)
  tag("nuna_aparece", rangos.nuna_aparece.desde, rangos.nuna_aparece.hasta, 1)
end)
app.refresh()
app.alert("Listo: apagado, encendido, calibrando, error y nuna_aparece. Guarda con Ctrl+S.")
