local function imagen(rows)
  local img = Image(80, 80, ColorMode.RGB)
  for y = 1, #rows do
    local r = rows[y]
    for x = 1, #r do
      local c = r:sub(x, x)
      if c ~= "." then img:drawPixel(x - 1, y - 1, COLORES[c]) end
    end
  end
  return img
end

app.transaction("Cama 303: sacude + arrugada", function()
  local rangos = {}
  for _, f in ipairs(FRAMES) do
    local fr = spr:newEmptyFrame(#spr.frames + 1)
    fr.duration = f.ms / 1000
    spr:newCel(capa, fr, imagen(f.rows), Point(0, 0))
    local r = rangos[f.tag]
    if not r then rangos[f.tag] = { desde = fr.frameNumber, hasta = fr.frameNumber }
    else r.hasta = fr.frameNumber end
  end
  local function tag(nombre, desde, hasta, rep)
    local t = spr:newTag(desde, hasta)
    t.name = nombre
    t.aniDir = AniDir.FORWARD
    t.repeats = rep
  end
  tag("tendida", 1, 1, 0)
  tag("sacude", rangos.sacude.desde, rangos.sacude.hasta, 2)
  tag("arrugada", rangos.arrugada.desde, rangos.arrugada.hasta, 0)
end)
app.refresh()
